#!/usr/bin/env python3
"""Generate the native RenderWare stub file.

The retail RenderWare API lives in ``source/game_sa/RenderWare/rw/*.cpp`` as thunks into
``gta_sa.exe``.  The native build compiles those files out and replaces them with the fakerw
layer in ``source/game_sa/RenderWare/librw/``.  Every symbol the rest of the game still
references has to exist, so this script emits, for every thunk that the fakerw layer does not
implement by hand, a definition with the same signature whose body logs ``Rw: stub <name>`` once
and returns a neutral value.

The signatures are taken verbatim from the thunks, so they always match the game headers.

Usage:
    python3 tools/native/gen_rw_stubs.py [--check]
"""

from __future__ import annotations

import argparse
import pathlib
import re
import sys

REPO = pathlib.Path(__file__).resolve().parents[2]
RW_DIR = REPO / "source/game_sa/RenderWare/rw"
FAKERW_DIR = REPO / "source/game_sa/RenderWare/librw"
OUTPUT = FAKERW_DIR / "RwStubs.generated.cpp"

# Matches a top-level function definition (the thunk files keep them at column 0, but a
# stripped `/*const*/`-style comment can leave leading blanks).
DEFINITION = re.compile(
    r"^[ \t]*([A-Za-z_][\w:\*&<>,\t ]*?)\b(\w+)\s*\(([^{};]*?)\)\s*\{",
    re.MULTILINE | re.DOTALL,
)


def strip_comments(text: str) -> str:
    text = re.sub(r"//[^\n]*", "", text)
    text = re.sub(r"/\*.*?\*/", "", text, flags=re.DOTALL)
    # Some thunks put the return type on its own line:
    #   RwBool
    #   RtAnimInterpolatorSetCurrentAnim(...)
    # join those so the definition regex sees one signature.
    text = re.sub(
        r"^([A-Za-z_][\w:]*[ \t]*\*?)[ \t]*\n[ \t]*([A-Za-z_]\w*[ \t]*\()",
        r"\1 \2",
        text,
        flags=re.MULTILINE,
    )
    return text


def parse_definitions(paths, warn: bool = True) -> dict[str, tuple[str, str, str]]:
    """Return ``name -> (return type, params, file)`` for every definition."""
    definitions: dict[str, tuple[str, str, str]] = {}
    for path in sorted(paths):
        text = strip_comments(path.read_text(encoding="utf-8", errors="replace"))
        for match in DEFINITION.finditer(text):
            return_type = " ".join(match.group(1).split())
            name = match.group(2)
            params = " ".join(match.group(3).split())
            if name in definitions:
                if warn:
                    print(f"warning: {name} defined twice ({definitions[name][2]}, {path.name})", file=sys.stderr)
                continue
            definitions[name] = (return_type, params, path.name)
    return definitions


def render(definitions: dict[str, tuple[str, str, str]]) -> str:
    # The thunks include the RenderWare headers that declare the types in their signatures;
    # `StdInc.h` does not include all of them (e.g. `rtslerp.h`), so mirror those includes here.
    includes = sorted(
        {
            match
            for path in RW_DIR.glob("*.cpp")
            for match in re.findall(r'^#include\s+("[\w.]+\.h")', strip_comments(path.read_text(encoding="utf-8", errors="replace")), re.MULTILINE)
            if match != '"StdInc.h"'
        }
    )

    lines = [
        "// Generated by tools/native/gen_rw_stubs.py - do not edit.",
        "//",
        "// Native counterparts of the retail RenderWare API entries that the fakerw layer does not",
        "// implement yet (see RwFakerw.h). Each one logs `Rw: stub <name>` once and returns a neutral",
        "// value; none of them call into gta_sa.exe.",
        "",
        '#include "StdInc.h"',
        "",
        "#ifdef NOTSA_NATIVE",
        "",
    ]
    lines.extend(f"#include {include}" for include in includes)
    lines.append("")
    lines.append('#include "RwFakerw.h"')
    lines.append("")

    for name, (return_type, params, _) in definitions.items():
        body = [f'    notsa::fakerw::Stub("{name}");']
        if return_type != "void":
            body.append("    return {};")
        lines.append(f"{return_type} {name}({params}) {{")
        lines.extend(body)
        lines.append("}")
        lines.append("")

    lines.append("#endif // NOTSA_NATIVE")
    lines.append("")
    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="fail if the generated file is stale")
    args = parser.parse_args()

    if not RW_DIR.is_dir():
        print(f"error: {RW_DIR} does not exist", file=sys.stderr)
        return 1

    thunks = parse_definitions(RW_DIR.glob("*.cpp"))
    implemented = parse_definitions(
        (p for p in FAKERW_DIR.glob("*.cpp") if p != OUTPUT),
        warn=False,
    )

    stubs = {
        name: definition
        for name, definition in thunks.items()
        if name not in implemented and not name.endswith("InjectHooks")
    }

    content = render(stubs)

    if args.check:
        if not OUTPUT.exists() or OUTPUT.read_text(encoding="utf-8") != content:
            print(f"error: {OUTPUT.relative_to(REPO)} is out of date", file=sys.stderr)
            return 1
        print(f"{OUTPUT.relative_to(REPO)} is up to date ({len(stubs)} stubs)")
        return 0

    OUTPUT.write_text(content, encoding="utf-8")
    print(f"{OUTPUT.relative_to(REPO)}: {len(stubs)} stubs ({len(thunks)} thunks, {len(implemented)} implemented)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
